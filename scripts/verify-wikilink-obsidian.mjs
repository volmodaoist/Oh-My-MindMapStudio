/** 普通节点 textarea 与导图内 CodeTab 原生编辑器的双链补全联测；只使用临时库。 */
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { launchObsidianHost } from './obsidian-host.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const codeTab = process.env.CODE_TAB_PLUGIN;
if (!codeTab) throw new Error('Set CODE_TAB_PLUGIN to the installed CodeTab artifact directory');
const initial = '---\nMindmap: Mindmap\nMindmap Layout: logical\n---\n\n## Plain\nDraft text\n\n## Alias\nAlias text\n\n## Heading\nHeading text\n\n## Escape\nEscape text\n\n## Tabs\n````tab\ntab: Notes\nMarkdown text\n````\n';
const host = await launchObsidianHost(initial, [{ id: 'obsidian-code-tab', path: codeTab }, { id: 'mindmap-studio', path: root }]);
const { page, directory, vault } = host;
page.setDefaultTimeout(10000);
const results = []; const errors = [];
const record = message => { results.push(message); console.log('PASS:', message); };
const commitTab = () => page.evaluate(async () => {
	const mounted = window.wikiHandles.find(item => item.container.isConnected && item.container.closest('[data-wiki-test]'));
	if (!mounted) throw new Error('Live CodeTab handle unavailable');
	await mounted.handle.commit();
});
page.on('pageerror', error => errors.push(error.stack ?? error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
try {
	await page.evaluate(async () => {
		for (const leaf of app.workspace.getLeavesOfType('mindmap-view')) leaf.detach();
		window.wikiHandles = [];
		const wrappers = new WeakMap();
		document.addEventListener('obsidian-code-tab-api', event => {
			const api = event.detail.api;
			if (!api) return;
			if (!wrappers.has(api)) wrappers.set(api, { ...api, render: async options => {
				const handle = await api.render(options); window.wikiHandles.push({ handle, container: options.container }); return handle;
			} });
			event.detail.api = wrappers.get(api);
		});
		await app.vault.createFolder('Topics');
		await app.vault.create('Topics/Target Note.md', '---\naliases: [Operating Systems]\n---\n\n# Quick Start\nText ^block-one\n');
		const leaf = app.workspace.getLeaf(true);
		await leaf.setViewState({ type: 'mindmap-view', state: { file: 'Test.mindmap.md' } });
		window.wikiTestView = leaf.view;
	});
	await page.waitForFunction(() => window.wikiTestView.mindMap && app.metadataCache.getFileCache(app.vault.getFileByPath('Topics/Target Note.md')));
	await page.evaluate(() => { window.wikiTestView.mindMap.el.setAttribute('data-wiki-test', ''); window.wikiTestView.mindMap.view.fit(); });
	const group = page.locator('[data-wiki-test] foreignObject .mindmap-plugin-live.code-tab').first();
	await group.getByTestId('code-tab-panel').filter({ visible: true }).getByText('Markdown text', { exact: true }).click();
	const native = group.locator('.code-tab__native-editor .cm-content');
	await native.waitFor(); await native.press('Meta+ArrowRight'); await native.pressSequentially(' [[Target');
	const candidate = page.locator('.cm-tooltip-autocomplete:visible .cm-completionLabel').filter({ hasText: 'Target Note' });
	await candidate.first().waitFor({ timeout: 10000 });
	await native.press('Enter');
	assert.equal(await group.getByTestId('code-tab-editor').count(), 1);
	await commitTab();
	await page.waitForFunction(async () => (await app.vault.read(app.vault.getFileByPath('Test.mindmap.md'))).includes('[[Target Note]]'));
	record('CodeTab native Markdown editor selects a wiki candidate without saving on Enter; explicit save persists the link');
	await page.locator('[data-wiki-test] foreignObject').getByText('Draft text', { exact: true }).dblclick();
	const input = page.locator('textarea.mindmap-node-inline-editor');
	await input.waitFor(); await input.pressSequentially(' [[Target');
	await page.locator('.mindmap-wikilink-suggestions .suggestion-title').filter({ hasText: 'Target Note' }).first().waitFor();
	const unfinished = await input.inputValue();
	await input.press('Tab');
	assert.equal(await input.count(), 1); assert((await input.inputValue()).includes('[[Target Note]]'));
	const completed = await input.inputValue();
	await input.press('Meta+Z'); assert.equal(await input.inputValue(), unfinished);
	await input.press('Meta+Shift+Z'); assert.equal(await input.inputValue(), completed);
	await input.press('Enter');
	await page.waitForFunction(async () => (await app.vault.read(app.vault.getFileByPath('Test.mindmap.md'))).includes('Draft text [[Target Note]]'));
	record('Node textarea completes a wiki link with Tab, retains the editor, then commits through the existing pipeline');
	await page.locator('[data-wiki-test] foreignObject').getByText('Alias text', { exact: true }).dblclick();
	await input.waitFor(); await input.pressSequentially(' [[Operating');
	const alias = page.locator('.mindmap-wikilink-suggestions .suggestion-title').filter({ hasText: 'Operating Systems' });
	await alias.first().click();
	assert((await input.inputValue()).includes('[[Target Note|Operating Systems]]')); assert.equal(await input.count(), 1);
	await input.press('Enter');
	record('Node alias mouse selection keeps focus and formats the native file path with alias');
	await page.locator('[data-wiki-test] foreignObject').getByText('Heading text', { exact: true }).dblclick();
	await input.waitFor(); await input.pressSequentially(' [[Target Note#Quick');
	await page.locator('.mindmap-wikilink-suggestions .suggestion-title').filter({ hasText: 'Quick Start' }).first().waitFor();
	await input.press('Enter'); assert((await input.inputValue()).includes('[[Target Note#Quick Start]]'));
	await input.press('Enter');
	record('Node heading suggestions use the native metadata cache');
	await page.locator('[data-wiki-test] foreignObject').getByText('Escape text', { exact: true }).dblclick();
	await input.waitFor(); await input.pressSequentially(' [[Tar');
	await page.locator('.mindmap-wikilink-suggestions').waitFor(); await input.press('Escape');
	assert.equal(await input.count(), 1); assert.equal(await page.locator('.mindmap-wikilink-suggestions:visible').count(), 0);
	await input.press('Meta+A'); await input.pressSequentially('Escape text'); await input.press('Enter');
	record('Escape closes node suggestions before the editor and leaves the existing node commit semantics intact');
	await page.evaluate(async () => { await app.workspace.revealLeaf(window.wikiTestView.leaf); window.wikiTestView.mindMap.view.fit(); });
	await group.getByTestId('code-tab-panel').filter({ visible: true }).locator('p').first().click({ position: { x: 1, y: 1 } });
	await native.waitFor(); await native.press('Meta+ArrowRight'); await native.pressSequentially(' [[Operating');
	await page.locator('.cm-tooltip-autocomplete:visible .cm-completionLabel').filter({ hasText: 'Operating Systems' }).first().click();
	assert.equal(await group.getByTestId('code-tab-editor').count(), 1);
	await commitTab();
	await page.waitForFunction(async () => (await app.vault.read(app.vault.getFileByPath('Test.mindmap.md'))).includes('Markdown text [[Target Note]] [[Target Note|Operating Systems]]'));
	record('CodeTab alias mouse selection uses its existing completion interaction guard and shared save pipeline');
	await page.evaluate(async () => { await app.workspace.revealLeaf(window.wikiTestView.leaf); window.wikiTestView.mindMap.view.fit(); });
	await group.getByTestId('code-tab-panel').filter({ visible: true }).locator('p').first().click({ position: { x: 1, y: 1 } });
	await native.waitFor(); await native.press('Meta+ArrowRight'); await native.pressSequentially(' [[Target Note#^block');
	await page.locator('.cm-tooltip-autocomplete:visible .cm-completionLabel').filter({ hasText: 'block-one' }).first().waitFor();
	await native.press('Tab');
	assert.equal(await group.getByTestId('code-tab-editor').count(), 1);
	assert((await native.innerText()).includes('[[Target Note#^block-one]]'));
	await commitTab();
	await page.waitForFunction(async () => (await app.vault.read(app.vault.getFileByPath('Test.mindmap.md'))).includes('[[Target Note#^block-one]]'));
	record('CodeTab Tab accepts block references and retains the editor until explicit save');
	await page.evaluate(async () => { await app.workspace.revealLeaf(window.wikiTestView.leaf); window.wikiTestView.mindMap.view.fit(); });
	await group.getByTestId('code-tab-panel').filter({ visible: true }).locator('p').first().click({ position: { x: 1, y: 1 } });
	await native.waitFor(); await native.press('Meta+ArrowRight'); await native.pressSequentially(' [[Tar');
	await page.locator('.cm-tooltip-autocomplete:visible').waitFor(); await native.press('Escape');
	assert.equal(await group.getByTestId('code-tab-editor').count(), 1);
	assert.equal(await page.locator('.cm-tooltip-autocomplete:visible').count(), 0);
	for (let index = 0; index < 6; index++) await native.press('Backspace');
	await commitTab();
	record('CodeTab Escape closes suggestions first and does not submit or cancel the Markdown editor');
	await page.evaluate(async () => { await window.wikiTestView.session.flush(); });
	const persisted = await readFile(join(vault, 'Test.mindmap.md'), 'utf8');
	await page.evaluate(async () => {
		const leaf = app.workspace.getLeaf(true);
		window.wikiTestView.leaf.detach();
		await leaf.setViewState({ type: 'mindmap-view', state: { file: 'Test.mindmap.md' } });
		window.wikiTestView = leaf.view;
	});
	await page.waitForFunction(() => window.wikiTestView.mindMap);
	await page.waitForFunction(() => document.querySelector('.mindmap-canvas-container .code-tab'));
	assert.equal(await readFile(join(vault, 'Test.mindmap.md'), 'utf8'), persisted);
	assert(persisted.includes('Draft text [[Target Note]]') && persisted.includes('[[Target Note#^block-one]]'));
	record('Reopening preserves both completed links and the Markdown source without an extra write');
	await page.evaluate(() => {
		const map = window.wikiTestView.mindMap;
		map.el.setAttribute('data-wiki-test', '');
		map.execCommand('INSERT_CHILD_NODE', true, [map.renderer.root], { text: '', isActive: false });
	});
	const empty = page.locator('.smm-node-edit-wrap:visible');
	await empty.waitFor(); await empty.pressSequentially('first'); await empty.press('Shift+Enter'); await empty.pressSequentially('😀 [[Tar');
	await page.locator('.mindmap-wikilink-suggestions .suggestion-title').filter({ hasText: 'Target Note' }).first().waitFor();
	await empty.press('Tab');
	assert.equal(await empty.count(), 1); assert((await empty.innerText()).includes('😀 [[Target Note]]'));
	await empty.press('Enter');
	await page.waitForFunction(async () => (await app.vault.read(app.vault.getFileByPath('Test.mindmap.md'))).includes('😀 [[Target Note]]'));
	assert.equal(await page.locator('.mindmap-wikilink-suggestions').count(), 0);
	record('New empty node retains native editing and completes after a BR and emoji, then saves through the original engine path');
	assert.deepEqual(errors, []);
	await page.screenshot({ path: join(directory, 'wikilink-completion.png'), fullPage: true });
	await writeFile(join(directory, 'report.json'), JSON.stringify({ ok: true, results, errors }, null, 2));
	console.log('PASS:', results.length, 'checks; artifacts:', directory);
} catch (error) {
	await writeFile(join(directory, 'report.json'), JSON.stringify({ ok: false, results, errors, error: String(error) }, null, 2));
	await writeFile(join(directory, 'failure.html'), await page.content().catch(() => '')).catch(() => undefined);
	await page.screenshot({ path: join(directory, 'failure.png'), fullPage: true }).catch(() => undefined);
	await writeFile(join(directory, 'report.json'), JSON.stringify({ ok: false, results, errors, error: String(error) }, null, 2));
	console.error('FAILED; artifacts:', directory); throw error;
} finally { await host.close(); }
